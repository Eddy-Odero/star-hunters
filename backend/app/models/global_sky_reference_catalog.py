def _make_entry(
    *,
    object_id: str,
    label: str,
    catalog: str,
    object_type: str,
    object_class: str,
    ra: float,
    dec: float,
    magnitude: float | None,
    proper_motion_arcsec_yr: float | None,
    w1_w2_color: float | None,
    constellation: str,
    target_name: str | None = None,
) -> dict[str, Any]:
    return {
        "object_id": object_id,
        "label": label,
        "catalog": catalog,
        "object_type": object_type,
        "object_class": object_class,
        "ra": round(float(ra), 5),
        "dec": round(float(dec), 5),
        "x": 128.0,
        "y": 128.0,
        "magnitude": magnitude,
        "proper_motion_arcsec_yr": proper_motion_arcsec_yr,
        "w1_w2_color": w1_w2_color,
        "default_checked": False,
        "epoch_positions": [],
        "constellation": constellation,
        "target_name": target_name or label,
        "patch_ra": round(float(ra), 4),
        "patch_dec": round(float(dec), 4),
        "data_source": "all_sky_reference_catalog",
    }


